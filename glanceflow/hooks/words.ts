/** The languages GlanceFlow speaks: its own words, and the words it asks Claude to use on the checklist. */
export type Lang = 'en' | 'el'

let lang: Lang = 'en'

/** Sets the language every later `tr` speaks; the language setting and session start call it. */
export const setLang = (next: Lang) => {
  lang = next
}

export const currentLang = (): Lang => lang

/**
 * GlanceFlow's own words in the person's language. The English is the key, so a line with no translation yet stays
 * English rather than breaking. `{0}`, `{1}` … stand for the values that follow, in either language. A key may end in
 * `#context` when one English line needs two translations; the English never shows it.
 */
export function tr(key: string, ...values: readonly (string | number)[]): string {
  const english = key.split('#')[0]!
  const text = lang === 'el' ? (GREEK[key] ?? english) : english
  return values.reduce<string>((out, value, at) => out.replaceAll(`{${at}}`, String(value)), text)
}

